const KIND = {
  event: 'This is an event: it turns true on the bar it happens, and inside a combination it keeps counting for the next few bars (the window, 3 by default), so it can meet the other checks.',
  state: 'This is a state: it is true on every bar where it holds, so it works best as a filter beside an event.',
};

/** The info card for one check: { title, what, how, when, trap, kind, put, rule }. Always returns something. */
export function infoFor(cond) {
  const fam = FAMILIES.find((f) => f.match.test(cond.key)) ?? null;
  return {
    family: fam?.title ?? cond.group,
    rule: cond.text,
    what: fam?.what ?? null,
    how: fam?.how ?? null,
    when: fam?.when ?? null,
    trap: fam?.trap ?? null,
    kind: KIND[cond.kind] ?? null,
    put: cond.group === 'Time of day' ? 'It has no direction: it is the same for calls and puts.' : 'For a put the same check is read upside down (a fall instead of a rise), so every check has a put twin.',
  };
}
